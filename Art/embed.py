"""Writes a model made in Blender into the package, as base64 in Swift, for
Sources/NullmereModels/Asset.swift to read: no resource bundle to carry into
the app, the same bytes on the Mac and on Linux.

    python3 Art/embed.py <model.glb> <out.swift> <enum> <name> [<maker script>]

The file it writes is generated: change the model in Blender (its script in
Art/blender) and run this again.
"""
import base64
import sys
import textwrap

source, out, enum, name = sys.argv[1:5]
maker = sys.argv[5] if len(sys.argv) > 5 else None
data = open(source, "rb").read()
lines = textwrap.wrap(base64.b64encode(data).decode("ascii"), 100)
made = f" (made by {maker})" if maker else ""
with open(out, "w") as f:
    f.write(f"// Generated by Art/embed.py from {source}{made}.\n")
    f.write("// Don't edit it: make the model again and run Art/embed.py.\n\n")
    f.write(f"extension {enum} {{\n")
    f.write(f"    /// {source}: {len(data)} bytes of glTF binary.\n")
    f.write(f"    static let {name} = \"\"\"\n")
    for line in lines:
        f.write(f"        {line}\n")
    f.write("        \"\"\"\n}\n")
print(f"{out}: {len(data)} bytes as {len(lines)} lines")
